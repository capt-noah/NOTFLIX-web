-- RPC: update_user_profile (with robust UPSERT)
CREATE OR REPLACE FUNCTION public.update_user_profile(
    p_user_id UUID,
    p_username TEXT,
    p_avatar_url TEXT
)
RETURNS SETOF public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    INSERT INTO public.profiles (id, username, avatar_url, updated_at)
    VALUES (p_user_id, p_username, p_avatar_url, NOW())
    ON CONFLICT (id)
    DO UPDATE SET
        username = EXCLUDED.username,
        avatar_url = EXCLUDED.avatar_url,
        updated_at = NOW();

    RETURN QUERY SELECT * FROM public.profiles WHERE id = p_user_id;
END;
$$;


-- 2. WATCHLIST TABLE
CREATE TABLE IF NOT EXISTS public.watchlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    media_id BIGINT NOT NULL,
    media_type TEXT NOT NULL,
    poster_path TEXT,
    title TEXT,
    rating NUMERIC DEFAULT 8.5,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_user_media UNIQUE (user_id, media_id, media_type)
);

CREATE INDEX IF NOT EXISTS idx_watchlist_user_id ON public.watchlist(user_id);

-- RPC: get_my_watchlist
CREATE OR REPLACE FUNCTION public.get_my_watchlist(u_id UUID)
RETURNS TABLE (
    media_id BIGINT,
    media_type TEXT,
    poster_path TEXT,
    title TEXT,
    rating NUMERIC
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT w.media_id, w.media_type, w.poster_path, w.title, COALESCE(w.rating, 8.5) AS rating
    FROM public.watchlist w
    WHERE w.user_id = u_id
    ORDER BY w.created_at DESC;
END;
$$;

-- RPC: toggle_watchlist_item (preserves rating)
CREATE OR REPLACE FUNCTION public.toggle_watchlist_item(
    u_id UUID,
    m_id BIGINT,
    m_type TEXT,
    p_path TEXT,
    t_title TEXT,
    p_rating NUMERIC DEFAULT 8.5
)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    item_exists BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM public.watchlist
        WHERE user_id = u_id AND media_id = m_id AND media_type = m_type
    ) INTO item_exists;

    IF item_exists THEN
        DELETE FROM public.watchlist
        WHERE user_id = u_id AND media_id = m_id AND media_type = m_type;
        RETURN 'removed';
    ELSE
        INSERT INTO public.watchlist (user_id, media_id, media_type, poster_path, title, rating)
        VALUES (u_id, m_id, m_type, p_path, t_title, COALESCE(p_rating, 8.5));
        RETURN 'added';
    END IF;
END;
$$;

-- RPC: is_in_watchlist
CREATE OR REPLACE FUNCTION public.is_in_watchlist(
    u_id UUID,
    m_id BIGINT,
    m_type TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.watchlist
        WHERE user_id = u_id AND media_id = m_id AND media_type = m_type
    );
END;
$$;


-- 3. CONTINUE WATCHING TABLE
CREATE TABLE IF NOT EXISTS public.continue_watching (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    media_id BIGINT NOT NULL,
    media_type TEXT NOT NULL,
    title TEXT,
    poster_path TEXT,
    backdrop_path TEXT,
    progress NUMERIC DEFAULT 0,
    season_number INT,
    episode_number INT,
    last_watched TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_user_continue_media UNIQUE (user_id, media_id)
);

CREATE INDEX IF NOT EXISTS idx_continue_watching_user_id ON public.continue_watching(user_id);

-- RPC: get_my_continue_watching
CREATE OR REPLACE FUNCTION public.get_my_continue_watching(u_id UUID)
RETURNS TABLE (
    media_id BIGINT,
    media_type TEXT,
    backdrop_path TEXT,
    poster_path TEXT,
    title TEXT,
    progress NUMERIC,
    season_number INT,
    episode_number INT,
    last_watched TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        c.media_id, 
        c.media_type, 
        COALESCE(c.backdrop_path, c.poster_path) AS backdrop_path, 
        c.poster_path, 
        c.title, 
        c.progress, 
        c.season_number, 
        c.episode_number, 
        c.last_watched
    FROM public.continue_watching c
    WHERE c.user_id = u_id
    ORDER BY c.last_watched DESC;
END;
$$;

-- RPC: save_watch_progress (populates both backdrop and poster)
CREATE OR REPLACE FUNCTION public.save_watch_progress(
    u_id UUID,
    m_id BIGINT,
    m_type TEXT,
    t_title TEXT,
    p_path TEXT,
    p_progress NUMERIC,
    s_num INT DEFAULT NULL,
    e_num INT DEFAULT NULL,
    b_path TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    INSERT INTO public.continue_watching (
        user_id, media_id, media_type, title, poster_path, backdrop_path, progress, season_number, episode_number, last_watched
    )
    VALUES (
        u_id, m_id, m_type, t_title, p_path, COALESCE(b_path, p_path), p_progress, s_num, e_num, NOW()
    )
    ON CONFLICT (user_id, media_id)
    DO UPDATE SET
        progress = EXCLUDED.progress,
        title = COALESCE(EXCLUDED.title, public.continue_watching.title),
        poster_path = COALESCE(EXCLUDED.poster_path, public.continue_watching.poster_path),
        backdrop_path = COALESCE(EXCLUDED.backdrop_path, EXCLUDED.poster_path, public.continue_watching.backdrop_path),
        season_number = COALESCE(EXCLUDED.season_number, public.continue_watching.season_number),
        episode_number = COALESCE(EXCLUDED.episode_number, public.continue_watching.episode_number),
        last_watched = NOW();
END;
$$;

-- RPC: remove_watch_progress
CREATE OR REPLACE FUNCTION public.remove_watch_progress(
    p_user_id UUID,
    p_media_id BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    DELETE FROM public.continue_watching
    WHERE user_id = p_user_id AND media_id = p_media_id;
END;
$$;


-- 4. MEDIA COMMENTS & REVIEWS TABLE
CREATE TABLE IF NOT EXISTS public.media_comments (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    media_id BIGINT NOT NULL,
    rating NUMERIC DEFAULT 0,
    comment TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_media_comments_media_id ON public.media_comments(media_id);

-- RPC: fetch_media_comments
CREATE OR REPLACE FUNCTION public.fetch_media_comments(p_media_id BIGINT)
RETURNS TABLE (
    id UUID,
    user_id UUID,
    rating NUMERIC,
    comment TEXT,
    created_at TIMESTAMPTZ,
    username TEXT,
    avatar TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        mc.id,
        mc.user_id,
        mc.rating,
        mc.comment,
        mc.created_at,
        COALESCE(p.username, 'Anonymous') AS username,
        COALESCE(p.avatar_url, '') AS avatar
    FROM public.media_comments mc
    LEFT JOIN public.profiles p ON mc.user_id = p.id
    WHERE mc.media_id = p_media_id
    ORDER BY mc.created_at DESC;
END;
$$;

-- RPC: add_media_comment
CREATE OR REPLACE FUNCTION public.add_media_comment(
    p_user_id UUID,
    p_media_id BIGINT,
    p_rating NUMERIC,
    p_comment TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    INSERT INTO public.media_comments (user_id, media_id, rating, comment, created_at)
    VALUES (p_user_id, p_media_id, p_rating, p_comment, NOW());
END;
$$;


